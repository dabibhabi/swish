#!/usr/bin/env python3
"""Regenerate the entry index in CHANGELOG.md from docs/changelog/YYYY-MM.md.

Entries live in per-month files (docs/changelog/YYYY-MM.md, `### YYYY-MM-DD — title` headings).
CHANGELOG.md keeps a header plus a generated index between the INDEX markers.
Usage: python3 scripts/changelog_index.py          (rewrite the index)
       python3 scripts/changelog_index.py --check   (exit 1 if the index is stale)
"""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
MONTHS = ROOT / "docs" / "changelog"
INDEX = ROOT / "CHANGELOG.md"
START, END = "<!-- INDEX:START (generated by scripts/changelog_index.py) -->", "<!-- INDEX:END -->"
HEAD = re.compile(r"^### (\d{4}-\d{2}-\d{2}) — (.*)$")


def slug(text: str, seen: dict) -> str:
    # GitHub heading anchor: lowercase, drop punctuation (keep word chars, - and space), spaces -> '-'
    s = re.sub(r"[^\w\- ]", "", text.strip().lower()).replace(" ", "-")
    n = seen.get(s, 0)
    seen[s] = n + 1
    return s if n == 0 else f"{s}-{n}"


def entries(path: pathlib.Path):
    seen, fence = {}, False
    for line in path.read_text(encoding="utf-8").split("\n"):
        if line.lstrip().startswith("```"):
            fence = not fence
        m = None if fence else HEAD.match(line)
        if m:
            yield m.group(1), m.group(2), slug(line[4:], seen)


def build() -> str:
    out = [START, "", "Entries are stored per month in [`docs/changelog/`](docs/changelog/). Newest month first.", ""]
    for f in sorted(MONTHS.glob("????-??.md"), reverse=True):
        es = list(entries(f))
        out += [f"### {f.stem} ({len(es)} entries)", ""]
        out += [f"- {d} — [{t}](docs/changelog/{f.name}#{a})" for d, t, a in es]
        out.append("")
    out.append(END)
    return "\n".join(out)


def main() -> int:
    text = INDEX.read_text(encoding="utf-8")
    if START in text and END in text:
        head = text[: text.index(START)]
    else:
        head = text.rstrip("\n") + "\n\n"
    new = head + build() + "\n"
    if "--check" in sys.argv:
        return 0 if new == text else 1
    INDEX.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
